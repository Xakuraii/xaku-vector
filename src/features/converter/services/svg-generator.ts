import { escapeXml } from '../utils/filename-utils';

export interface SvgGeneratorOptions {
  dataUrl: string;
  width: number;
  height: number;
  title: string;
  description?: string;
}

/**
 * Builds a valid, standalone W3C SVG XML document wrapping raster data.
 * Maintains viewBox so the container is responsive and scales cleanly.
 */
export function buildSvgMarkup({
  dataUrl,
  width,
  height,
  title,
  description = 'Generated by XakuVector',
}: SvgGeneratorOptions): string {
  const safeWidth = Math.max(1, Math.round(width));
  const safeHeight = Math.max(1, Math.round(height));
  const safeTitle = escapeXml(title || 'XakuVector Output');
  const safeDesc = escapeXml(description);

  return [
    '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${safeWidth}" height="${safeHeight}" viewBox="0 0 ${safeWidth} ${safeHeight}" fill="none">`,
    `  <title>${safeTitle}</title>`,
    `  <desc>${safeDesc}</desc>`,
    `  <image width="${safeWidth}" height="${safeHeight}" preserveAspectRatio="xMidYMid meet" href="${dataUrl}" xlink:href="${dataUrl}" />`,
    '</svg>',
  ].join('\n');
}

/**
 * Computes exact UTF-8 byte size of the SVG string.
 */
export function getSvgByteLength(svgString: string): number {
  if (typeof Blob !== 'undefined') {
    return new Blob([svgString], { type: 'image/svg+xml;charset=utf-8' }).size;
  }
  // Fallback for Node/test environments without Blob
  return new TextEncoder().encode(svgString).length;
}

/**
 * Validates that an SVG XML string is well-formed using the browser's DOMParser.
 */
export function validateSvgXml(svgString: string): { isValid: boolean; error?: string } {
  if (typeof DOMParser === 'undefined') {
    return { isValid: true };
  }

  try {
    const parser = new DOMParser();
    const doc = parser.parseFromString(svgString, 'image/svg+xml');
    const parserError = doc.querySelector('parsererror');

    if (parserError) {
      return {
        isValid: false,
        error: parserError.textContent || 'XML parsing error',
      };
    }

    const svgElement = doc.querySelector('svg');
    if (!svgElement) {
      return {
        isValid: false,
        error: 'No root <svg> element found in document',
      };
    }

    return { isValid: true };
  } catch (err) {
    return {
      isValid: false,
      error: err instanceof Error ? err.message : 'Unknown parsing error',
    };
  }
}
